// lib/clipboard/richCopy.js
// Write text/html + text/plain to the clipboard so Outlook / Word paste the formatted version and plain-text targets get
// the text version. Order of attempts:
//   1. navigator.clipboard.write([ClipboardItem({text/html, text/plain})])   (async Clipboard API)
//   2. execCommand('copy') on a hidden contenteditable holding the HTML      (older browsers / blocked ClipboardItem)
//   3. navigator.clipboard.writeText(text)                                   (plain text only)
// Browser only. The HTML passed in must already be safe (built from the parser AST, see docHtml / tableClipboard).

/** @returns {Promise<{ok: boolean, method: 'clipboard-item'|'exec-command'|'text'|null, rich: boolean}>} */
export async function copyRich({ html, text }) {
  const nav = typeof navigator !== 'undefined' ? navigator : null;
  if (nav?.clipboard?.write && typeof ClipboardItem !== 'undefined') {
    try {
      await nav.clipboard.write([new ClipboardItem({
        'text/html': new Blob([html], { type: 'text/html' }),
        'text/plain': new Blob([text], { type: 'text/plain' }),
      })]);
      return { ok: true, method: 'clipboard-item', rich: true };
    } catch { /* fall through */ }
  }
  if (typeof document !== 'undefined' && document.body && typeof document.execCommand === 'function') {
    const host = document.createElement('div');
    host.setAttribute('contenteditable', 'true');
    host.setAttribute('aria-hidden', 'true');
    host.style.cssText = 'position:fixed;left:-9999px;top:0;width:1px;height:1px;overflow:hidden;opacity:0;white-space:pre-wrap;';
    // The HTML is generated by our own escaping writer from the safe AST; it is not user markup.
    host.innerHTML = html;
    document.body.appendChild(host);
    const prev = document.activeElement;
    let ok = false;
    try {
      const range = document.createRange();
      range.selectNodeContents(host);
      const sel = window.getSelection();
      sel.removeAllRanges();
      sel.addRange(range);
      ok = document.execCommand('copy') === true;
      sel.removeAllRanges();
    } catch { ok = false; }
    host.remove();
    try { prev?.focus?.({ preventScroll: true }); } catch { /* ignore */ }
    if (ok) return { ok: true, method: 'exec-command', rich: true };
  }
  if (nav?.clipboard?.writeText) {
    try { await nav.clipboard.writeText(text); return { ok: true, method: 'text', rich: false }; } catch { /* fall through */ }
  }
  return { ok: false, method: null, rich: false };
}
